/* ═══════════════════════════════════════════════════════════
   i18n engine
   ═══════════════════════════════════════════════════════════ */
let currentLang = localStorage.getItem("oc-lang") || "es";

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem("oc-lang", lang);
  document.documentElement.lang = lang;
  applyTranslations();
  updateLangToggle();
}

function applyTranslations() {
  const dict = translations[currentLang] || translations.es;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) {
      if (el.tagName === "INPUT" && el.type !== "hidden") {
        // don't overwrite input values
      } else if (el.tagName === "OPTION" || el.tagName === "LABEL") {
        el.textContent = dict[key];
      } else {
        el.textContent = dict[key];
      }
    }
  });
}

function updateLangToggle() {
  const en = document.querySelector(".lang-label--en");
  const es = document.querySelector(".lang-label--es");
  if (en && es) {
    en.classList.toggle("active", currentLang === "en");
    es.classList.toggle("active", currentLang === "es");
  }
}

/* Init */
document.addEventListener("DOMContentLoaded", () => {
  applyTranslations();
  updateLangToggle();

  const toggle = document.getElementById("lang-toggle");
  if (toggle) {
    toggle.addEventListener("click", () => {
      setLang(currentLang === "es" ? "en" : "es");
    });
  }
});
