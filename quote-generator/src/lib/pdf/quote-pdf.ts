// Helpers
// ═══════════════════════════════════════

function formatCurrency(value: number): string {
  return `$${value.toLocaleString("en-US", {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  })}`;
}

function getConfidenceLabel(score: number, l: PdfLabels): string {
  if (score >= 0.8) return l.confidenceHigh;
  if (score >= 0.5) return l.confidenceMedium;
  return l.confidenceLow;
}

function getConfidenceColor(score: number): [number, number, number] {
  if (score >= 0.8) return COLORS.green;
  if (score >= 0.5) return COLORS.yellow;
  return COLORS.red;
}

function getUrgencyLabel(
  urgency: "high" | "normal" | "unknown",
  l: PdfLabels,
): string {
  switch (urgency) {
    case "high":
      return l.urgencyHigh;
    case "normal":
      return l.urgencyNormal;
    default:
      return l.urgencyUnknown;
  }
}

function shortId(id: string): string {
  return id.substring(0, 8).toUpperCase();
}

function getUnitLabel(unitType?: string): string {
  switch (unitType) {
    case "per_ton":
      return "/ton";
    case "per_cbm":
      return "/CBM";
    case "per_kg":
      return "/kg";
    default:
      return "";
  }
}

/**
 * Sanitize text for jsPDF's built-in Helvetica font (Windows-1252 only).
 * Replaces Unicode symbols with ASCII-safe equivalents to prevent
 * garbled output (e.g. arrows showing as "l'", stars as "&").
 */
function sanitizeText(text: string): string {
  return text
    .replace(/\u2192|\u2794|\u279C|\u27A1/g, " -> ")   // → arrows
    .replace(/\u2190/g, "<- ")                           // ←
    .replace(/\u2605|\u2B50/g, "* ")                     // ★ ⭐
    .replace(/\u26A0\uFE0F?/g, "! ")                     // ⚠️
    .replace(/\u2014/g, " - ")                            // — em dash
    .replace(/\u2013/g, "-")                              // – en dash
    .replace(/\u2018|\u2019/g, "'")                       // '' smart quotes
    .replace(/\u201C|\u201D/g, '"')                       // "" smart quotes
    .replace(/\u2022/g, "- ")                             // • bullet
    .replace(/\u00B7/g, ".")                              // · middle dot
    .replace(/\u2026/g, "...")                            // … ellipsis
    .replace(/\u00A0/g, " ")                              // non-breaking space
    .replace(/\u2713|\u2714/g, "[OK] ")                   // ✓ ✔
    .replace(/\u2717|\u2718/g, "[X] ")                    // ✗ ✘
    .replace(/\u00BD/g, "1/2")                            // ½
    .replace(/\u00BC/g, "1/4")                            // ¼
    .replace(/\u00BE/g, "3/4");                           // ¾
}

// ═══════════════════════════════════════
// Main Generator
// ═══════════════════════════════════════

export function generateQuotePdf(
  quote: QuoteDisplay,
  locale: Locale,
  options: PdfOptions = {},
): Blob | string | void {
  const { action = "save", filename, clientName, clientCompany } = options;

  const l = labels[locale];
  const doc = new jsPDF({
    orientation: "landscape",
    unit: "mm",
    format: "a4",
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 15;
  const contentWidth = pageWidth - margin * 2;
  let cursorY = 0;

  // ─── Header with gradient-like background ───
  drawHeader(doc, quote, l, locale, pageWidth, clientName, clientCompany);
  cursorY = 48;

  // ─── Quote Metadata ───
  cursorY = drawMetadata(doc, quote, l, margin, cursorY, contentWidth);

  // ─── Surcharge Notice (if applicable) ───
  const hasSurchargeIssues = quote.lines.some((line) =>
    line.surchargeFlags.some(
      (s) => s.status === "excluded" || s.status === "unknown",
    ),
  );
  if (hasSurchargeIssues) {
    cursorY = drawSurchargeNotice(doc, l, margin, cursorY, contentWidth);
  }

  // ─── Carrier Comparison Table ───
  cursorY = drawCarrierTable(doc, quote, l, margin, cursorY);

  // ─── AI Recommendation ───
  drawRecommendation(doc, quote, l, margin, cursorY, contentWidth);

  // ─── Footer on all pages ───
  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    drawFooter(doc, l, pageWidth, pageHeight, i, totalPages);
  }

  // ─── Output ───
  const defaultFilename =
    filename ||
    `OperisChain_Quote_${quote.cargo.origin.replace(/[^a-zA-Z]/g, "")}_${quote.cargo.destination.replace(/[^a-zA-Z]/g, "")}_${shortId(quote.quoteId)}`;

  switch (action) {
    case "save":
      doc.save(`${defaultFilename}.pdf`);
      return;
    case "blob":
      return doc.output("blob");
    case "datauri":
      return doc.output("datauristring");
  }
}

