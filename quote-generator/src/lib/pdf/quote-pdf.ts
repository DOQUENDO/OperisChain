function drawHeader(
  doc: jsPDF,
  quote: QuoteDisplay,
  l: PdfLabels,
  locale: Locale,
  pageWidth: number,
  clientName?: string,
  clientCompany?: string,
): void {
  // Dark background header bar
  doc.setFillColor(...COLORS.dark);
  doc.rect(0, 0, pageWidth, 44, "F");

  // Gradient accent line
  const gradientSteps = 80;
  const lineWidth = pageWidth / gradientSteps;
  for (let i = 0; i < gradientSteps; i++) {
    const ratio = i / gradientSteps;
    const r = Math.round(
      COLORS.primary[0] + (COLORS.secondary[0] - COLORS.primary[0]) * ratio,
    );
    const g = Math.round(
      COLORS.primary[1] + (COLORS.secondary[1] - COLORS.primary[1]) * ratio,
    );
    const b = Math.round(
      COLORS.primary[2] + (COLORS.secondary[2] - COLORS.primary[2]) * ratio,
    );
    doc.setFillColor(r, g, b);
    doc.rect(i * lineWidth, 44, lineWidth + 0.5, 2.5, "F");
  }

  // Logo text
  doc.setFont("helvetica", "bold");
  doc.setFontSize(20);
  doc.setTextColor(...COLORS.white);
  doc.text("OperisChain", 15, 16);

  // Title
  doc.setFontSize(11);
  doc.setTextColor(...COLORS.primary);
  doc.text(l.title, 15, 24);

  // Subtitle
  doc.setFontSize(8);
  doc.setTextColor(...COLORS.textMuted);
  doc.text(l.subtitle, 15, 30);

  // Right side — Quote ID + Date
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(...COLORS.textMuted);
  const rightX = pageWidth - 15;
  doc.text(`${l.quoteId}${shortId(quote.quoteId)}`, rightX, 14, {
    align: "right",
  });
  doc.text(
    sanitizeText(`${l.date}: ${new Date(quote.generatedAt).toLocaleDateString(locale === "es" ? "es-CO" : "en-US", { year: "numeric", month: "long", day: "numeric" })}`),
    rightX,
    20,
    { align: "right" },
  );

  // Client info (if provided)
  if (clientName || clientCompany) {
    doc.setTextColor(...COLORS.white);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.text(l.preparedFor, rightX, 30, { align: "right" });
    doc.setFont("helvetica", "normal");
    if (clientCompany) {
      doc.text(clientCompany, rightX, 35, { align: "right" });
    }
    if (clientName) {
      doc.text(clientName, rightX, clientCompany ? 40 : 35, {
        align: "right",
      });
    }
  }
}

function drawMetadata(
  doc: jsPDF,
  quote: QuoteDisplay,
  l: PdfLabels,
  margin: number,
  startY: number,
  contentWidth: number,
): number {
  const y = startY + 6;
  const colWidth = contentWidth / 4;

  // Background card
  doc.setFillColor(...COLORS.darkCard);
  doc.roundedRect(margin, y - 3, contentWidth, 18, 2, 2, "F");

  const metaItems = [
    {
      label: l.route,
      value: sanitizeText(`${quote.cargo.origin} -> ${quote.cargo.destination}`),
    },
    { label: l.weight, value: `${quote.cargo.weightKg.toLocaleString()} kg` },
    { label: l.urgency, value: getUrgencyLabel(quote.cargo.urgency, l) },
    {
      label: l.carrierComparison,
      value: `${quote.lines.length} carriers`,
    },
  ];

  metaItems.forEach((item, i) => {
    const x = margin + 6 + i * colWidth;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7);
    doc.setTextColor(...COLORS.textMuted);
    doc.text(item.label, x, y + 4);

    doc.setFont("helvetica", "bold");
    doc.setFontSize(10);
    doc.setTextColor(...COLORS.white);
    doc.text(item.value, x, y + 10);
  });

  return y + 20;
}

function drawSurchargeNotice(
  doc: jsPDF,
  l: PdfLabels,
  margin: number,
  startY: number,
  contentWidth: number,
): number {
  const y = startY + 2;

  // Yellow-ish warning box
  doc.setFillColor(234, 179, 8);
  doc.roundedRect(margin, y, contentWidth, 10, 1.5, 1.5, "F");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(7.5);
  doc.setTextColor(...COLORS.black);
  doc.text(l.surchargeWarning, margin + 4, y + 4);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(7);
  doc.text(l.surchargeNote, margin + 4, y + 8);

  return y + 14;
}

function drawCarrierTable(
  doc: jsPDF,
  quote: QuoteDisplay,
  l: PdfLabels,
  margin: number,
  startY: number,
): number {
  // Sort lines by score descending (same as UI default)
  const sortedLines = [...quote.lines].sort((a, b) => b.score - a.score);

  const tableHead = [
    [
      "",
      l.carrier,
      l.routeCol,
      l.price,
      l.unitPrice,
      l.transit,
      l.validUntil,
      l.confidence,
      l.score,
    ],
  ];

  const tableBody = sortedLines.map((line) => {
    const isRecommended = line.carrier === quote.recommended;
    const totalPrice =
      line.totalPriceUSD != null ? line.totalPriceUSD : line.priceUSD;
    const unitType = line.unitType || "per_kg";
    const isUnitRate =
      unitType === "per_kg" || unitType === "per_ton" || unitType === "per_cbm";

    return [
      isRecommended ? "*" : "",
      sanitizeText(line.carrier),
      sanitizeText(line.route),
      formatCurrency(totalPrice),
      isUnitRate && totalPrice !== line.priceUSD
        ? `${formatCurrency(line.priceUSD)}${getUnitLabel(unitType)}`
        : "-",
      line.transitDays != null ? `${line.transitDays} ${l.days}` : l.na,
      line.validUntil || l.na,
      getConfidenceLabel(line.confidenceScore, l),
      `${(line.score * 100).toFixed(0)}`,
    ];
  });

  autoTable(doc, {
    startY: startY + 2,
    head: tableHead,
    body: tableBody,
    margin: { left: margin, right: margin },
    theme: "plain",
    styles: {
      font: "helvetica",
      fontSize: 8,
      cellPadding: { top: 3, bottom: 3, left: 3, right: 3 },
      textColor: COLORS.text,
      lineColor: [30, 30, 46],
      lineWidth: 0.2,
    },
    headStyles: {
      fillColor: COLORS.tableHead,
      textColor: COLORS.white,
      fontStyle: "bold",
      fontSize: 7.5,
      halign: "left",
    },
    columnStyles: {
      0: {
        cellWidth: 8,
        halign: "center",
        fontSize: 10,
        textColor: COLORS.primary,
      },
      1: { fontStyle: "bold", cellWidth: 35 },
      2: { cellWidth: 30 },
      3: { halign: "right", fontStyle: "bold", cellWidth: 28 },
      4: {
        halign: "right",
        fontSize: 7,
        textColor: COLORS.textMuted,
        cellWidth: 25,
      },
      5: { halign: "center", cellWidth: 22 },
      6: { halign: "center", cellWidth: 25 },
      7: { halign: "center", cellWidth: 22 },
      8: { halign: "center", fontStyle: "bold", cellWidth: 18 },
    },
    alternateRowStyles: {
      fillColor: COLORS.tableAlt,
    },
    didParseCell: (data) => {
      // Fill color for recommended row
      if (data.section === "body") {
        const lineIndex = data.row.index;
        const line = sortedLines[lineIndex];
        if (line && line.carrier === quote.recommended) {
          data.cell.styles.fillColor = [0, 40, 50]; // Dark cyan tint
        }

        // Confidence column color
        if (data.column.index === 7 && line) {
          data.cell.styles.textColor = getConfidenceColor(line.confidenceScore);
        }

        // Score column color
        if (data.column.index === 8) {
          data.cell.styles.textColor = COLORS.primary;
        }
      }
    },
  });

  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  return (doc as any).lastAutoTable.finalY + 4;
}

function drawRecommendation(
  doc: jsPDF,
  quote: QuoteDisplay,
  l: PdfLabels,
  margin: number,
  startY: number,
  contentWidth: number,
): number {
  let y = startY + 2;

  // Check if we need a new page
  const pageHeight = doc.internal.pageSize.getHeight();
  if (y + 40 > pageHeight - 20) {
    doc.addPage();
    y = 20;
  }

  // Recommendation card background
  doc.setFillColor(...COLORS.darkCard);
  const recommendedLine = quote.lines.find(
    (line) => line.carrier === quote.recommended,
  );

  // Calculate text height for the reasoning
  doc.setFontSize(8);
  const reasoningLines = doc.splitTextToSize(
    sanitizeText(quote.reasoning),
    contentWidth - 16,
  );
  const cardHeight = Math.max(30, 22 + reasoningLines.length * 3.5);

  doc.roundedRect(margin, y, contentWidth, cardHeight, 2, 2, "F");

  // Cyan left accent bar
  doc.setFillColor(...COLORS.primary);
  doc.rect(margin, y, 2.5, cardHeight, "F");

  // Title
  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.setTextColor(...COLORS.primary);
  doc.text(l.recommendationTitle, margin + 8, y + 7);

  // Recommended carrier + score
  if (recommendedLine) {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(12);
    doc.setTextColor(...COLORS.white);
    doc.text(
      sanitizeText(`${quote.recommended} - ${formatCurrency(recommendedLine.totalPriceUSD ?? recommendedLine.priceUSD)}`),
      margin + 8,
      y + 14,
    );

    // Score badge
    const scoreText = `${(recommendedLine.score * 100).toFixed(0)}/100`;
    const scoreX = margin + contentWidth - 30;
    doc.setFillColor(...COLORS.primary);
    doc.roundedRect(scoreX, y + 4, 22, 8, 2, 2, "F");
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.setTextColor(...COLORS.dark);
    doc.text(scoreText, scoreX + 11, y + 9.5, { align: "center" });
  }

  // Reasoning text
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.setTextColor(...COLORS.textMuted);
  doc.text(reasoningLines, margin + 8, y + 20);

  return y + cardHeight + 4;
}

function drawFooter(
  doc: jsPDF,
  l: PdfLabels,
  pageWidth: number,
  pageHeight: number,
  currentPage: number,
  totalPages: number,
): void {
  const footerY = pageHeight - 12;

  // Separator line
  doc.setDrawColor(...COLORS.textMuted);
  doc.setLineWidth(0.2);
  doc.line(15, footerY - 2, pageWidth - 15, footerY - 2);

  // Disclaimer
  doc.setFont("helvetica", "italic");
  doc.setFontSize(6);
  doc.setTextColor(...COLORS.textMuted);
  doc.text(l.footerDisclaimer, 15, footerY + 1);

  // Powered by
  doc.setFont("helvetica", "normal");
  doc.setFontSize(6.5);
  doc.setTextColor(...COLORS.primary);
  doc.text(l.footer, pageWidth / 2, footerY + 5, { align: "center" });

  // Page number
  doc.setTextColor(...COLORS.textMuted);
  doc.text(
    `${l.page} ${currentPage} ${l.of} ${totalPages}`,
    pageWidth - 15,
    footerY + 5,
    { align: "right" },
  );
}
