/**
 * OperisChain — Quote PDF Generator
 *
 * Client-side PDF generation using jsPDF + AutoTable.
 *
 * Architecture:
 * - Pure function (no React dependency) — can be used from hooks, API routes, or tests
 * - Bilingual (ES/EN) via Locale parameter
 * - Branded with OperisChain gradient header
 * - Scalable: add new sections by implementing PdfSection interface
 *
 * Usage:
 *   import { generateQuotePdf } from '@/lib/pdf/quote-pdf';
 *   const blob = generateQuotePdf(quoteData, 'es');
 *   // or save:
 *   generateQuotePdf(quoteData, 'es', { action: 'save' });
 */

